# One-time developer setup for ChordKu on Windows.
#   1. points cargo at the CMake bundled with Visual Studio (libopus needs it)
#   2. exports the BTC chord model to ONNX (Python is used here only, never at runtime)
#   3. installs and builds the web UI
# The beat tracker and the stem separator are downloaded from inside the app (Pengaturan > Model).

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

Write-Host "== 1/3 CMake for cargo" -ForegroundColor Cyan
$cmake = (Get-Command cmake -ErrorAction SilentlyContinue).Source
if (-not $cmake) {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (Test-Path $vswhere) {
        $cmake = & $vswhere -latest -products * -find "Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe" | Select-Object -First 1
    }
}
if (-not $cmake) { throw "CMake not found. Install 'C++ CMake tools for Windows' from the Visual Studio Installer, or cmake.org." }
New-Item -ItemType Directory -Force (Join-Path $root ".cargo") | Out-Null
$cfg = "# Generated by tools/setup.ps1 (machine specific, not committed).`n[env]`nCMAKE = { value = `"$($cmake -replace '\\','/')`", force = false }`n"
Set-Content -Path (Join-Path $root ".cargo\config.toml") -Value $cfg -Encoding utf8
Write-Host "   $cmake"

Write-Host "== 2/3 BTC chord model -> models\btc.onnx" -ForegroundColor Cyan
$export = Join-Path $root "tools\export"
$py = Join-Path $export ".venv\Scripts\python.exe"
if (-not (Test-Path $py)) {
    python -m venv (Join-Path $export ".venv")
    & $py -m pip install -q --upgrade pip
    & $py -m pip install -q torch --index-url https://download.pytorch.org/whl/cpu
    & $py -m pip install -q librosa onnx onnxruntime onnxscript numpy soundfile pyyaml
}
$btc = Join-Path $export "_vendor\btc"
if (-not (Test-Path $btc)) {
    git clone -q --depth 1 https://github.com/jayg996/BTC-ISMIR19.git $btc
}
if (-not (Test-Path (Join-Path $root "models\btc.onnx"))) {
    Push-Location $export
    & $py export_btc.py
    Pop-Location
} else {
    Write-Host "   models\btc.onnx already present"
}

Write-Host "== 3/3 web UI" -ForegroundColor Cyan
Push-Location (Join-Path $root "web")
npm install --no-fund --no-audit
npm run build
Pop-Location

Write-Host "`nSelesai. Jalankan: tools\run.ps1" -ForegroundColor Green
